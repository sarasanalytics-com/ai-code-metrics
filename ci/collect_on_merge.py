"""CI-level commit attribution collector.

Runs in GitHub Actions on merge to protected branches (dev/qa/prod).
Classifies commits by parsing commit messages — no git-ai dependency needed.
This is tamper-resistant because developers cannot modify commit messages
after merge (branch protection prevents force-push).
"""

import json
import os
import re
import subprocess
import sys
from collections import defaultdict
from dataclasses import dataclass
from datetime import date, datetime


@dataclass
class MergedCommit:
    sha: str
    author: str
    author_email: str
    date: date
    message: str
    lines_added: int = 0
    lines_removed: int = 0
    tool: str = "human"


def classify_commit(message: str) -> str:
    """Classify a commit based on its message. Priority order:

    1. Co-Authored-By trailers (tamper-resistant — part of commit SHA)
    2. Commit message patterns
    """
    msg_lower = message.lower()

    # Parse Co-Authored-By trailers individually to avoid false positives
    # (e.g., "noreply.github.com" in human co-author emails)
    co_authors = re.findall(r'co-authored-by:\s*(.+)', msg_lower)
    for co_author in co_authors:
        if "claude" in co_author or "anthropic" in co_author:
            return "claude"
        if "windsurf" in co_author or "codeium" in co_author:
            return "windsurf"
        if "cursor" in co_author:
            return "cursor"
        if "copilot" in co_author:
            return "copilot"

    # Commit message patterns
    if "generated by windsurf" in msg_lower or "[windsurf]" in msg_lower:
        return "windsurf"
    if "generated by cursor" in msg_lower:
        return "cursor"

    return "human"


def get_merge_commits(base_sha: str, head_sha: str) -> list[MergedCommit]:
    """Get all commits between base and head (the commits being merged)."""
    log_format = "%H%x00%an%x00%ae%x00%aI%x00%B%x00"
    separator = "%x01"

    result = subprocess.run(
        [
            "git", "log",
            f"--format={separator}{log_format}",
            "--numstat",
            f"{base_sha}..{head_sha}",
        ],
        capture_output=True,
        text=True,
        timeout=120,
    )

    if result.returncode != 0:
        print(f"Error reading git log: {result.stderr}", file=sys.stderr)
        return []

    commits = []
    for entry in result.stdout.split("\x01"):
        entry = entry.strip()
        if not entry:
            continue

        parts = entry.split("\x00", 5)
        if len(parts) < 5:
            continue

        sha, author, email, date_str, message = (
            parts[0].strip(),
            parts[1].strip(),
            parts[2].strip(),
            parts[3].strip(),
            parts[4].strip(),
        )

        remaining = parts[5] if len(parts) > 5 else ""
        added = 0
        removed = 0
        for line in remaining.strip().splitlines():
            nums = line.split("\t")
            if len(nums) >= 2:
                try:
                    added += int(nums[0])
                except ValueError:
                    pass
                try:
                    removed += int(nums[1])
                except ValueError:
                    pass

        try:
            dt = datetime.fromisoformat(date_str)
            commit_date = dt.date()
        except (ValueError, TypeError):
            continue

        tool = classify_commit(message)

        commits.append(MergedCommit(
            sha=sha,
            author=author,
            author_email=email,
            date=commit_date,
            message=message,
            lines_added=added,
            lines_removed=removed,
            tool=tool,
        ))

    return commits


def build_summary(repo: str, branch: str, commits: list[MergedCommit]) -> dict:
    """Build a JSON summary of the merge for downstream processing."""
    by_tool = defaultdict(lambda: {
        "commits": 0,
        "lines_added": 0,
        "lines_removed": 0,
        "authors": set(),
    })

    for c in commits:
        by_tool[c.tool]["commits"] += 1
        by_tool[c.tool]["lines_added"] += c.lines_added
        by_tool[c.tool]["lines_removed"] += c.lines_removed
        by_tool[c.tool]["authors"].add(c.author)

    summary = {
        "repo": repo,
        "branch": branch,
        "collected_at": datetime.utcnow().isoformat(),
        "total_commits": len(commits),
        "breakdown": {},
        "commits": [],
    }

    for tool, stats in by_tool.items():
        summary["breakdown"][tool] = {
            "commits": stats["commits"],
            "lines_added": stats["lines_added"],
            "lines_removed": stats["lines_removed"],
            "unique_authors": len(stats["authors"]),
        }

    for c in commits:
        summary["commits"].append({
            "sha": c.sha,
            "author": c.author,
            "date": c.date.isoformat(),
            "tool": c.tool,
            "lines_added": c.lines_added,
            "lines_removed": c.lines_removed,
        })

    return summary


def write_job_summary(summary: dict):
    """Write a markdown summary to the GitHub Actions job summary."""
    summary_path = os.environ.get("GITHUB_STEP_SUMMARY", "")
    if not summary_path:
        return

    total = summary["total_commits"]
    breakdown = summary["breakdown"]

    # Calculate AI vs Human totals
    ai_lines = sum(s["lines_added"] for t, s in breakdown.items() if t != "human")
    human_lines = breakdown.get("human", {}).get("lines_added", 0)
    total_lines = ai_lines + human_lines
    ai_pct = round((ai_lines / total_lines) * 100, 1) if total_lines > 0 else 0

    lines = []
    lines.append("## AI Code Metrics")
    lines.append("")
    lines.append(f"**{summary['repo']}** / `{summary['branch']}` — {total} commit{'s' if total != 1 else ''}")
    lines.append("")

    # Overall AI percentage bar
    bar_filled = round(ai_pct / 5)
    bar_empty = 20 - bar_filled
    bar = "█" * bar_filled + "░" * bar_empty
    lines.append(f"**AI Contribution:** `{bar}` {ai_pct}%")
    lines.append("")

    # Breakdown table
    lines.append("| Source | Commits | Lines Added | Lines Removed | Authors |")
    lines.append("|--------|---------|-------------|---------------|---------|")
    for tool, stats in sorted(breakdown.items()):
        icon = {"claude": "🤖", "windsurf": "🏄", "copilot": "🧑‍✈️", "cursor": "🖱️", "human": "👤"}.get(tool, "❓")
        lines.append(
            f"| {icon} {tool.capitalize()} "
            f"| {stats['commits']} "
            f"| +{stats['lines_added']} "
            f"| -{stats['lines_removed']} "
            f"| {stats['unique_authors']} |"
        )
    lines.append("")

    # Commit details
    lines.append("<details>")
    lines.append("<summary>Commit details</summary>")
    lines.append("")
    lines.append("| SHA | Author | Tool | +/- |")
    lines.append("|-----|--------|------|-----|")
    for c in summary["commits"]:
        lines.append(
            f"| `{c['sha'][:8]}` "
            f"| {c['author']} "
            f"| {c['tool']} "
            f"| +{c['lines_added']}/−{c['lines_removed']} |"
        )
    lines.append("")
    lines.append("</details>")

    with open(summary_path, "a") as f:
        f.write("\n".join(lines) + "\n")


def main():
    # Read from GitHub Actions environment
    repo = os.environ.get("GITHUB_REPOSITORY", "unknown")
    branch = os.environ.get("GITHUB_REF_NAME", "unknown")
    base_sha = os.environ.get("BASE_SHA", "")
    head_sha = os.environ.get("HEAD_SHA", "HEAD")
    output_file = os.environ.get("OUTPUT_FILE", "metrics_output.json")

    if not base_sha:
        # Fallback: get the merge base from the event
        event_path = os.environ.get("GITHUB_EVENT_PATH", "")
        if event_path and os.path.exists(event_path):
            with open(event_path) as f:
                event = json.load(f)
            base_sha = event.get("before", "")

    if not base_sha:
        print("Error: BASE_SHA not set and could not be determined", file=sys.stderr)
        sys.exit(1)

    # Extract repo name (org/repo -> repo)
    repo_name = repo.split("/")[-1] if "/" in repo else repo

    print(f"Collecting metrics for {repo_name} ({base_sha[:8]}..{head_sha[:8]}) on {branch}")

    commits = get_merge_commits(base_sha, head_sha)
    print(f"Found {len(commits)} commits")

    if not commits:
        print("No commits to process")
        return

    summary = build_summary(repo_name, branch, commits)

    # Print breakdown
    for tool, stats in summary["breakdown"].items():
        print(f"  {tool}: {stats['commits']} commits, +{stats['lines_added']}/−{stats['lines_removed']} lines")

    # Write output
    with open(output_file, "w") as f:
        json.dump(summary, f, indent=2)
    print(f"Output written to {output_file}")

    # Set GitHub Actions output
    github_output = os.environ.get("GITHUB_OUTPUT", "")
    if github_output:
        with open(github_output, "a") as f:
            f.write(f"total_commits={len(commits)}\n")
            ai_commits = sum(
                s["commits"] for t, s in summary["breakdown"].items() if t != "human"
            )
            f.write(f"ai_commits={ai_commits}\n")
            f.write(f"human_commits={summary['breakdown'].get('human', {}).get('commits', 0)}\n")

    # Write GitHub Actions job summary
    write_job_summary(summary)


if __name__ == "__main__":
    main()
